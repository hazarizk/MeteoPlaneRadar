#!/usr/bin/env python3
"""Generate MeteoPlaneRadar/TzHistory.h - every change of the clock in
Central Europe from 1800 to 2100, for the planets screen's time travel.

The device converts between UTC and local time with the rule in force NOW
(TimeZone.*), which is right for the clock and wrong for 1987: the summer
time of that year began on a different Sunday, the summer time of 1947 ran
under a different rule again, and from December 1946 to February 1947 the
clocks in Czechoslovakia stood on GMT. Before October 1891 Prague kept its own
mean time, 57 minutes 44 seconds ahead of Greenwich. A birth chart drawn for
"14:00" needs the offset that was on the wall that day, not today's.

So this reads the IANA zone Europe/Prague from the system's tz database
through Python's zoneinfo, finds every instant the offset changed, and writes
them out as a table the firmware can search. Future years come from the EU
rule in the same database.

    python3 tools/tz_history.py          # writes the header
    python3 tools/tz_history.py -v       # and lists the transitions

Needs Python 3.9+ and a tz database (macOS and Linux have one; on Windows
`pip install tzdata`).
"""
import os
import sys
from datetime import datetime, timedelta, timezone
from zoneinfo import ZoneInfo

ZONE = "Europe/Prague"
FIRST = datetime(1800, 1, 1, tzinfo=timezone.utc)
LAST = datetime(2101, 1, 1, tzinfo=timezone.utc)

HERE = os.path.dirname(os.path.abspath(__file__))


def offset_at(tz, t):
    return int(t.astimezone(tz).utcoffset().total_seconds())


def transitions(tz):
    """[(utc epoch, offset seconds, abbreviation)] - the offset before the
    first entry is the entry for FIRST itself."""
    out = [(int(FIRST.timestamp()), offset_at(tz, FIRST), FIRST.astimezone(tz).tzname())]
    t = FIRST
    step = timedelta(hours=6)
    cur = out[0][1]
    while t < LAST:
        n = t + step
        o = offset_at(tz, n)
        if o != cur:
            # Bisect to the second between t and n.
            lo, hi = t, n
            while (hi - lo).total_seconds() > 1:
                mid = lo + (hi - lo) / 2
                if offset_at(tz, mid) != cur:
                    hi = mid
                else:
                    lo = mid
            # hi is within a second after the change; walk back to the exact one.
            c = int(hi.timestamp())
            while offset_at(tz, datetime.fromtimestamp(c - 1, timezone.utc)) == o:
                c -= 1
            out.append((c, o, hi.astimezone(tz).tzname()))
            cur = o
        t = n
    return out


def emit(path, rows):
    L = []
    L.append("// =============================================================================")
    L.append("//  MeteoPlaneRadar")
    L.append(f"//  TzHistory.h - every change of the clock in {ZONE}, 1800-2100.")
    L.append("//")
    L.append("//  GENERATED by tools/tz_history.py from the IANA tz database. Used by")
    L.append("//  TimeZone_OffsetAt() so that the planets screen, set to some day in the")
    L.append("//  past, converts with the offset that was on the wall that day: summer time")
    L.append("//  under the rules of its own year, the GMT winter of 1946/47, Prague mean")
    L.append("//  time before 1891. Each row is the UTC instant a new offset began and that")
    L.append("//  offset in seconds east of UTC; the first row is the state at 1800-01-01.")
    L.append("//")
    L.append("//  Project: MeteoPlaneRadar - live aircraft radar on a round touchscreen")
    L.append("//  Author:  Petr / chiptron.cz   (vyvoj / development: chiptron.cz)")
    L.append("// =============================================================================")
    L.append("#pragma once")
    L.append("#include <Arduino.h>")
    L.append("")
    L.append("struct TzChange { int64_t at; int32_t off; };")
    L.append("")
    L.append(f"#define TZ_HISTORY_ZONE \"{ZONE}\"")
    L.append(f"#define TZ_HISTORY_N {len(rows)}")
    L.append("")
    L.append("static const TzChange TZ_HISTORY[TZ_HISTORY_N] = {")
    for at, off, abbr in rows:
        when = datetime.fromtimestamp(at, timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
        h, rem = divmod(abs(off), 3600)
        m, s = divmod(rem, 60)
        sgn = "+" if off >= 0 else "-"
        human = f"{sgn}{h}:{m:02d}" + (f":{s:02d}" if s else "")
        L.append(f"  {{ {at:>12}LL, {off:>5} }},   // {when} UTC -> {human} {abbr}")
    L.append("};")
    L.append("")
    with open(path, "w") as f:
        f.write("\n".join(L))


if __name__ == "__main__":
    tz = ZoneInfo(ZONE)
    rows = transitions(tz)
    emit(os.path.join(HERE, "..", "MeteoPlaneRadar", "TzHistory.h"), rows)
    print(f"{len(rows)} entries for {ZONE}")
    if "-v" in sys.argv:
        for at, off, abbr in rows:
            print(datetime.fromtimestamp(at, timezone.utc).strftime("%Y-%m-%d %H:%M:%S"), f"{off:>6}", abbr)
